#!/usr/bin/env bash
# Create (once) and prepare the isolated DSH development profile used to verify
# dsh-remote without touching the user's real ~/.dsh.
#
#   ./scripts/dev-profile.sh [profile-name]
#
# Environment:
#   DSH_DEV_HOME  defaults to <repo>/.dsh-test (exported to the child as DSH_HOME)
#   PROFILE    defaults to remotedev
#
# The profile is created from the shipped headless template, uses the user's
# saved DeepSeek credentials (symlinked, never copied), disables no tools, and
# selects the deepseek-flash model.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export DSH_HOME="${DSH_DEV_HOME:-$REPO_DIR/.dsh-test}"
PROFILE="${1:-${PROFILE:-remotedev}}"
PROFILE_DIR="$DSH_HOME/profiles/$PROFILE"

case "$PROFILE" in
  *[!A-Za-z0-9_-]* | '')
    echo "invalid profile name: $PROFILE" >&2
    exit 2
    ;;
esac

mkdir -p "$DSH_HOME"

if [ ! -d "$PROFILE_DIR" ]; then
  echo "creating profile $PROFILE in $DSH_HOME"
  dsh --profile "$PROFILE" --from-default-profile headless --dump-config >/dev/null
fi

# Credentials: the headless template disables the managed credential store. Link
# the real saved credentials into the isolated home and re-enable the rows so
# the profile can reach the DeepSeek account exactly like the desktop app.
if [ -f "$HOME/.dsh/.credentials.yaml" ]; then
  ln -sfn "$HOME/.dsh/.credentials.yaml" "$DSH_HOME/.credentials.yaml"
else
  echo "warning: $HOME/.dsh/.credentials.yaml not found; the dev profile needs API credentials" >&2
fi

cat >"$PROFILE_DIR/cordis.patch.yml" <<'YAML'
# dsh-remote development profile (generated by scripts/dev-profile.sh)
- id: credentials
  disabled: false
- id: authorization
  disabled: false
- id: deepseek-account
  disabled: false
- id: agent-default-model
  name: '@deepseek-ai/dsh-agent-default-model'
  config:
    provider: deepseek-account
    model: deepseek-flash
    reasoningEffort: high
YAML

# Ensure the bundle row exists even before the first `dsh plugin add`.
node - "$PROFILE_DIR/package.json" <<'NODE'
const fs = require("node:fs");
const file = process.argv[2];
const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
manifest.dsh ??= {};
manifest.dsh.profile ??= {};
manifest.dsh.profile.bundles ??= [];
if (!manifest.dsh.profile.bundles.includes("dsh-remote")) {
  manifest.dsh.profile.bundles.push("dsh-remote");
  fs.writeFileSync(file, `${JSON.stringify(manifest, null, 2)}\n`);
}
NODE

echo "profile ready: DSH_HOME=$DSH_HOME profile=$PROFILE"
